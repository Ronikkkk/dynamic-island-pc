const { contextBridge, ipcRenderer, webFrame } = require('electron');

// Периодическая уборка памяти: сбрасываем кэш картинок движка (обложки, фон блюра) — они
// всё равно подгрузятся заново, если понадобятся.
ipcRenderer.on('mem-trim', () => { try { webFrame.clearCache(); } catch (e) {} });

contextBridge.exposeInMainWorld('api', {
  hover: (over) => ipcRenderer.send('hover', !!over),
  screenshot: () => ipcRenderer.send('screenshot'),
  focus: (on) => ipcRenderer.invoke('focus', !!on),
  sysStats: () => ipcRenderer.invoke('sys-stats'),
  weather: () => ipcRenderer.invoke('weather'),
  onFocusLive: (cb) => ipcRenderer.on('focus-live', (_e, d) => cb(d)),
  onApp: (cb) => ipcRenderer.on('app-live', (_e, d) => cb(d)),
  appsLoad: () => ipcRenderer.invoke('apps-load'),
  appsSave: (d) => ipcRenderer.invoke('apps-save', d),
  appsPick: () => ipcRenderer.invoke('apps-pick'),
  appIcon: (p) => ipcRenderer.invoke('app-icon', String(p)),
  appLaunch: (p) => ipcRenderer.invoke('app-launch', String(p)),
  notesLoad: () => ipcRenderer.invoke('notes-load'),
  notesSave: (d) => ipcRenderer.invoke('notes-save', d),
  favsLoad: () => ipcRenderer.invoke('favs-load'),
  favsSave: (d) => ipcRenderer.invoke('favs-save', d),
  soundLoad: () => ipcRenderer.invoke('sound-load'),
  soundPick: () => ipcRenderer.invoke('sound-pick'),
  soundClear: () => ipcRenderer.invoke('sound-clear'),
  mediaOpenTrack: (t) => ipcRenderer.invoke('media-open-track', t),
  vol: (mode, level) => ipcRenderer.invoke('vol', mode, level),
  statAdd: (n) => ipcRenderer.send('stat-add', String(n)),
  licStatus: () => ipcRenderer.invoke('lic-status'),
  licMachine: () => ipcRenderer.invoke('lic-machine'),
  licActivate: (k) => ipcRenderer.invoke('lic-activate', String(k || '')),
  notifAct: (act, app) => ipcRenderer.invoke('notif-act', String(act), String(app)),
  onCall: (cb) => ipcRenderer.on('callstate', (_e, d) => cb(d)),
  notifGet: () => ipcRenderer.invoke('notif-get'),
  notifSet: (on) => ipcRenderer.invoke('notif-set', !!on),
  onNotif: (cb) => ipcRenderer.on('notif', (_e, d) => cb(d)),
  openBuy: () => ipcRenderer.send('open-buy'),
  openTg: () => ipcRenderer.send('open-tg'),
  daySummary: () => ipcRenderer.invoke('day-summary'),
  mediaFocus: (id) => ipcRenderer.invoke('media-focus', String(id || '')),
  focusWin: () => ipcRenderer.send('focus-window'),
  designLoad: () => ipcRenderer.invoke('design-load'),
  designSave: (d) => ipcRenderer.invoke('design-save', d),
  designImage: () => ipcRenderer.invoke('design-image'),
  designImageClear: () => ipcRenderer.invoke('design-image-clear'),
  customLoad: () => ipcRenderer.invoke('custom-load'),
  customSave: (d) => ipcRenderer.invoke('custom-save', d),
  customDragStart: (sx, sy) => ipcRenderer.send('custom-drag-start', sx, sy),
  customDragMove: (dx, dy) => ipcRenderer.invoke('custom-drag-move', dx, dy),
  customDragEnd: () => ipcRenderer.invoke('custom-drag-end'),
  customReset: () => ipcRenderer.invoke('custom-reset'),
  blurActive: (on) => ipcRenderer.send('blur-active', !!on),
  onBlurBg: (cb) => ipcRenderer.on('blur-bg', (_e, d) => cb(d)),
  onGreet: (cb) => ipcRenderer.on('greet', (_e, t) => cb(t)),
  autohideGet: () => ipcRenderer.invoke('autohide-get'),
  autohideSet: (on) => ipcRenderer.invoke('autohide-set', !!on),
  autostartGet: () => ipcRenderer.invoke('autostart-get'),
  autostartSet: (on) => ipcRenderer.invoke('autostart-set', !!on),
  hide: () => ipcRenderer.send('hide'),
  quit: () => ipcRenderer.send('quit'),
  mediaCmd: (cmd) => ipcRenderer.send('media-cmd', String(cmd)),
  langGet: () => { try { return ipcRenderer.sendSync('lang-get-sync'); } catch (e) { return 'ru'; } },
  langSet: (l) => ipcRenderer.invoke('lang-set', String(l || 'ru')),
  onLicRevoked: (cb) => ipcRenderer.on('lic-revoked', () => cb()),
  onVis: (cb) => ipcRenderer.on('vis', (_e, d) => cb(d)),
  onMedia: (cb) => ipcRenderer.on('media', (_e, data) => cb(data)),
  on: (channel, cb) => {
    if (channel === 'toggle' || channel === 'timer' || channel === 'focus') {
      ipcRenderer.on(channel, () => cb());
    }
  }
});
